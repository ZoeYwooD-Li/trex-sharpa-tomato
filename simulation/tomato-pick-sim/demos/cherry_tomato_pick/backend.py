class CherryTomatoPickBackend:
    """Small-batch task backend shared by standalone and RL entry points.

    Each environment owns an independent Newton model.  This preserves real
    rigid contact and selected resets for the first port; it is intentionally a
    correctness backend, not yet the final replicated-world training backend.
    """

    accepts_torch = False
    supports_snapshot_reset = True

    def __init__(
        self,
        cfg: dict[str, Any],
        *,
        num_envs: int = 1,
        device: str = "cpu",
        randomize: bool = False,
        enable_visual_assets: bool = True,
        seed: int = 42,
        config_path: Path | None = None,
    ) -> None:
        if num_envs <= 0:
            raise ValueError("num_envs must be positive")
        self.cfg = deepcopy(cfg)
        self.num_envs = int(num_envs)
        self.device = str(device)
        self.randomize = bool(randomize)
        self.rng = np.random.default_rng(seed)
        self.config_path = config_path
        cache_raw = Path(self.cfg.get("assets", {}).get("cache_dir", ".cache/lycheesim/cherry_tomato_pick"))
        self.repository_root = Path(__file__).resolve().parents[2]
        if not cache_raw.is_absolute():
            cache_raw = self.repository_root / cache_raw
        self.cache_dir = cache_raw
        self.assets = ensure_procedural_assets(cache_raw, self.cfg)
        self.visual_meshes = (
            load_optional_visual_assets(self.repository_root, self.cfg)
            if enable_visual_assets
            else {}
        )
        self.scenes = [self._make_scene() for _ in range(self.num_envs)]
        self.physics_dt = self.scenes[0].physics_dt
        self._commands = np.zeros((self.num_envs, 10), dtype=np.float32)

    def _randomized_cfg(self) -> dict[str, Any]:
        cfg = deepcopy(self.cfg)
        if not self.randomize:
            return cfg
        randomization = cfg.get("rl", {}).get("randomization", {})
        xy = float(randomization.get("position_xy_m", 0.0))
        delta = self.rng.uniform(-xy, xy, size=2).astype(np.float32)
        for key in ("tomato_position", "stem_anchor"):
            value = np.asarray(cfg["scene"][key], dtype=np.float32)
            value[:2] += delta
            cfg["scene"][key] = value.tolist()
        break_fraction = float(randomization.get("break_force_fraction", 0.0))
        cfg["attachment"]["break_force_N"] *= float(
            self.rng.uniform(1.0 - break_fraction, 1.0 + break_fraction)
        )
        mass_fraction = float(randomization.get("tomato_mass_fraction", 0.0))
        cfg["scene"]["tomato_mass_kg"] *= float(
            self.rng.uniform(1.0 - mass_fraction, 1.0 + mass_fraction)
        )
        return cfg

    def _make_scene(self) -> _TomatoScene:
        scene = _TomatoScene(
            self._randomized_cfg(),
            self.assets,
            self.visual_meshes,
            device=self.device,
            repository_root=self.repository_root,
            cache_dir=self.cache_dir,
        )
        if self.randomize and bool(
            self.cfg.get("rl", {}).get("start_from_pregrasp", True)
        ):
            scene.set_robot_state(
                scene.robot.left_pregrasp_tcp,
                scene.robot.right_pregrasp_tcp,
                0.0,
                0.0,
            )
        return scene

    def seed(self, seed: int) -> None:
        self.rng = np.random.default_rng(seed)

    def set_robot_command(self, command: np.ndarray) -> None:
        value = np.asarray(command, dtype=np.float32)
        if value.shape == (10,) and self.num_envs == 1:
            value = value[None, :]
        if value.shape != (self.num_envs, 10):
            raise ValueError(
                f"dual-arm command must have shape {(self.num_envs, 10)}, got {value.shape}"
            )
        self._commands = value.copy()

    def set_robot_states(
        self,
        left_tcp_poses: np.ndarray,
        right_tcp_poses: np.ndarray,
        hand_closures: np.ndarray,
    ) -> None:
        left = np.asarray(left_tcp_poses, dtype=np.float64).reshape(self.num_envs, 7)
        right = np.asarray(right_tcp_poses, dtype=np.float64).reshape(self.num_envs, 7)
        closures = np.asarray(hand_closures, dtype=np.float32).reshape(
            self.num_envs, 2
        )
        for index, scene in enumerate(self.scenes):
            scene.set_robot_state(
                left[index],
                right[index],
                float(closures[index, 0]),
                float(closures[index, 1]),
            )

    def set_cluster_offsets(self, offsets: np.ndarray) -> None:
        values = np.asarray(offsets, dtype=np.float32)
        if values.shape == (3,) and self.num_envs == 1:
            values = values[None, :]
        if values.shape != (self.num_envs, 3):
            raise ValueError(
                "cluster carrier offsets must have shape "
                f"{(self.num_envs, 3)}, got {values.shape}"
            )
        for index, scene in enumerate(self.scenes):
            scene.set_cluster_offset(values[index])

    def set_left_retentions(self, amounts: np.ndarray) -> None:
        values = np.asarray(amounts, dtype=np.float32).reshape(self.num_envs)
        for index, scene in enumerate(self.scenes):
            scene.set_left_retention(float(values[index]))

    def step(self) -> None:
        for index, scene in enumerate(self.scenes):
            scene.command = self._commands[index].copy()
            scene.step()

    def refresh(self) -> None:
        for scene in self.scenes:
            scene.refresh()

    def reset(self, env_ids=None) -> None:
        if env_ids is None:
            ids = np.arange(self.num_envs, dtype=np.int64)
        else:
            if hasattr(env_ids, "detach"):
                env_ids = env_ids.detach().cpu().numpy()
            ids = np.asarray(env_ids, dtype=np.int64).reshape(-1)
        for index in ids:
            if index < 0 or index >= self.num_envs:
                raise IndexError(f"environment index out of range: {index}")
            self.scenes[int(index)] = self._make_scene()
            self._commands[int(index)] = 0.0

    def read_signals(self) -> dict[str, np.ndarray]:
        rows = [scene.read_signals() for scene in self.scenes]
        return {
            name: np.stack([np.asarray(row[name], dtype=np.float32) for row in rows])
            for name in rows[0]
        }

    @property
    def primary_scene(self) -> _TomatoScene:
        return self.scenes[0]

    def close(self) -> None:
        self.scenes.clear()


