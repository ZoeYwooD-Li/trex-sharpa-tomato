"""Newton rigid-contact backend for dual-arm cherry-tomato harvesting.

The tomato is a dynamic rigid body held by a task-local breakable stem model.
The latest upstream workflow is preserved: the right FR3/Wuji2 presses the
opposite branch endpoint while the left FR3/Wuji2 grasps and lifts the target.
Newton contact is generated by the ten official Beta2 fingertip sensor pads.
All public quaternions are ``xyzw``.
"""

