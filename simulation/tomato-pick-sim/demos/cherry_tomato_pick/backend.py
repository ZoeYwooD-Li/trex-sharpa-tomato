@dataclass(frozen=True)
class AttachmentParams:
    anchor: np.ndarray
    local_point: np.ndarray
    break_direction_world: np.ndarray
    axial_stiffness: float
    lateral_stiffness: float
    axial_damping: float
    lateral_damping: float
    bending_stiffness: float
    torsional_stiffness: float
    bending_damping: float
    torsional_damping: float
    break_force_N: float
    break_torque_Nm: float
    rest_quaternion_xyzw: np.ndarray | None = None


@dataclass
class _AttachmentFailureState:
    """Filtered, persistent overload state for one breakable pedicel."""

    dt: float
    ema_time_constant_s: float
    minimum_overload_s: float
    filtered_load: float = 0.0
    overload_duration_s: float = 0.0

    def __post_init__(self) -> None:
        if self.dt <= 0.0:
            raise ValueError("attachment failure dt must be positive")
        if self.ema_time_constant_s <= 0.0:
            raise ValueError("attachment EMA time constant must be positive")
        if self.minimum_overload_s <= 0.0:
            raise ValueError("attachment overload duration must be positive")

    def update(self, raw_load: float, *, armed: bool) -> bool:
        alpha = 1.0 - np.exp(-self.dt / self.ema_time_constant_s)
        self.filtered_load += float(alpha) * (
            max(0.0, float(raw_load)) - self.filtered_load
        )
        if armed and self.filtered_load >= 1.0:
            self.overload_duration_s += self.dt
        else:
            self.overload_duration_s = 0.0
        return self.overload_duration_s + 1.0e-12 >= self.minimum_overload_s


@dataclass(frozen=True)
class VisualMeshAsset:
    vertices: np.ndarray
    faces: np.ndarray
    normals: np.ndarray
    uvs: np.ndarray
    texture: np.ndarray
    texture_path: Path
    body_name: str
    local_position: tuple[float, float, float] = (0.0, 0.0, 0.0)


def _quat_rotate_xyzw(quaternion: np.ndarray, vector: np.ndarray) -> np.ndarray:
    xyz = np.asarray(quaternion[:3], dtype=np.float64)
    w = float(quaternion[3])
    value = np.asarray(vector, dtype=np.float64)
    cross = 2.0 * np.cross(xyz, value)
    return value + w * cross + np.cross(xyz, cross)


def attachment_wrench(
    params: AttachmentParams,
    *,
    position: np.ndarray,
    quaternion_xyzw: np.ndarray,
    linear_velocity: np.ndarray,
    angular_velocity: np.ndarray,
    torsion_enabled: bool = True,
    anchor_velocity: np.ndarray | None = None,
    parent_angular_velocity: np.ndarray | None = None,
) -> tuple[np.ndarray, np.ndarray, float, float]:
    """Return stem force, torque, force load, and torque load.

    The point spring models the compliant pedicel before failure. Axial and
    lateral translation, plus bending and twist rotation, have independent
    stiffness and damping. Loads are normalized by the upstream prototype's
    break thresholds. Only tensile force along the configured pedicel axis
    contributes to the force break load; compression and lateral contact still
    affect the constraint wrench but cannot fracture the attachment.
    """

    offset = _quat_rotate_xyzw(quaternion_xyzw, params.local_point)
    point = np.asarray(position, dtype=np.float64) + offset
    point_velocity = np.asarray(linear_velocity, dtype=np.float64) + np.cross(
        np.asarray(angular_velocity, dtype=np.float64), offset
    )
    if anchor_velocity is not None:
        point_velocity -= anchor_velocity
    if parent_angular_velocity is not None:
        angular_velocity = np.asarray(angular_velocity) - parent_angular_velocity
    break_direction = np.asarray(params.break_direction_world, dtype=np.float64)
    break_direction_norm = float(np.linalg.norm(break_direction))
    if break_direction.shape != (3,) or break_direction_norm <= 0.0:
        raise ValueError("break_direction_world must be a nonzero XYZ vector")
    break_direction /= break_direction_norm

    translation_error = params.anchor - point
    axial_error = float(np.dot(translation_error, break_direction))
    lateral_error = translation_error - axial_error * break_direction
    axial_velocity = float(np.dot(point_velocity, break_direction))
    lateral_velocity = point_velocity - axial_velocity * break_direction
    force = (
        params.axial_stiffness * axial_error * break_direction
        + params.lateral_stiffness * lateral_error
        - params.axial_damping * axial_velocity * break_direction
        - params.lateral_damping * lateral_velocity
    )
    rest_quaternion = (
        np.asarray((0.0, 0.0, 0.0, 1.0), dtype=np.float64)
        if params.rest_quaternion_xyzw is None
        else np.asarray(params.rest_quaternion_xyzw, dtype=np.float64)
    )
    rotation_error = (
        Rotation.from_quat(quaternion_xyzw)
        * Rotation.from_quat(rest_quaternion).inv()
    ).as_rotvec()
    angular_velocity = np.asarray(angular_velocity, dtype=np.float64)
    twist_error = float(np.dot(rotation_error, break_direction))
    bending_error = rotation_error - twist_error * break_direction
    twist_velocity = float(np.dot(angular_velocity, break_direction))
    bending_velocity = angular_velocity - twist_velocity * break_direction
    angular_torque = (
        -params.bending_stiffness * bending_error
        - params.torsional_stiffness * twist_error * break_direction
        - params.bending_damping * bending_velocity
        - params.torsional_damping * twist_velocity * break_direction
    )
    torque = np.cross(offset, force) + angular_torque
    tensile_force = max(0.0, -float(np.dot(force, break_direction)))
    force_load = float(tensile_force / params.break_force_N)
    torque_load = (
        float(np.linalg.norm(angular_torque) / params.break_torque_Nm)
        if torsion_enabled
        else 0.0
    )
    return force.astype(np.float32), torque.astype(np.float32), force_load, torque_load


def _export_mesh_once(path: Path, mesh: trimesh.Trimesh) -> None:
    if path.is_file():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    mesh.export(path)


def ensure_procedural_assets(cache_dir: Path, cfg: dict[str, Any]) -> dict[str, Path]:
    """Create compact object collision geometry and a visual fallback."""

    scene = cfg["scene"]
    radius = float(scene["tomato_radius_m"])
    branch_length = float(scene["branch_length_m"])
    branch_radius = float(scene["branch_radius_m"])
    branch = trimesh.creation.cylinder(
        radius=branch_radius, height=branch_length, sections=24
    )
    configured_axis = scene.get("branch_collision_axis")
    if configured_axis is None:
        branch.apply_translation(
            (
                0.0,
                0.0,
                float(scene["stem_anchor"][2])
                + float(scene.get("branch_collision_clearance_m", 0.0))
                + 0.5 * branch_length
                - float(scene["tomato_position"][2]),
            )
        )
    else:
        axis = np.asarray(configured_axis, dtype=np.float64)
        norm = float(np.linalg.norm(axis))
        if norm <= 0.0:
            raise ValueError("scene.branch_collision_axis must be non-zero")
        branch.apply_transform(
            trimesh.geometry.align_vectors((0.0, 0.0, 1.0), axis / norm)
        )
        branch.apply_translation(
            np.asarray(scene["branch_collision_center_offset_m"], dtype=np.float64)
        )
    meshes = {
        "tomato": trimesh.creation.icosphere(subdivisions=3, radius=radius),
        "branch": branch,
    }
    paths: dict[str, Path] = {}
    for name, mesh in meshes.items():
        path = cache_dir / f"{name}_collision_v3.obj"
        _export_mesh_once(path, mesh)
        paths[name] = path
    return paths


def _load_visual_mesh(
    path: Path,
    texture: np.ndarray,
    texture_path: Path,
    *,
    body_name: str,
    local_position: tuple[float, float, float] = (0.0, 0.0, 0.0),
) -> VisualMeshAsset:
    with np.load(path) as payload:
        vertices = np.asarray(payload["vertices"], dtype=np.float32)
        faces = np.asarray(payload["faces"], dtype=np.int32)
        normals = np.asarray(payload["normals"], dtype=np.float32)
        uvs = np.asarray(payload["uvs"], dtype=np.float32)
    if vertices.ndim != 2 or vertices.shape[1] != 3:
        raise ValueError(f"visual vertices must have shape (N,3): {path}")
    if faces.ndim != 2 or faces.shape[1] != 3:
        raise ValueError(f"visual faces must have shape (F,3): {path}")
    if normals.shape != vertices.shape or uvs.shape != (len(vertices), 2):
        raise ValueError(f"visual normals/UVs do not match vertices: {path}")
    return VisualMeshAsset(
        vertices=vertices,
        faces=faces,
        normals=normals,
        uvs=uvs,
        texture=texture,
        texture_path=texture_path,
        body_name=body_name,
        local_position=local_position,
    )


def _visual_submesh(
    asset: VisualMeshAsset,
    face_indices: np.ndarray,
    *,
    body_name: str,
) -> VisualMeshAsset:
    """Return one indexed visual subset while preserving normals and UV seams."""

    faces = np.asarray(asset.faces[face_indices], dtype=np.int32)
    used_vertices = np.unique(faces.reshape(-1))
    remap = np.full(len(asset.vertices), -1, dtype=np.int32)
    remap[used_vertices] = np.arange(len(used_vertices), dtype=np.int32)
    return VisualMeshAsset(
        vertices=np.asarray(asset.vertices[used_vertices], dtype=np.float32),
        faces=remap[faces],
        normals=np.asarray(asset.normals[used_vertices], dtype=np.float32),
        uvs=np.asarray(asset.uvs[used_vertices], dtype=np.float32),
        texture=asset.texture,
        texture_path=asset.texture_path,
        body_name=body_name,
    )


def _split_target_pedicel_visual(
    stem: VisualMeshAsset,
    attachment_local_point: np.ndarray,
) -> tuple[VisualMeshAsset, VisualMeshAsset | None]:
    """Detach the target fruit's local green stem/calyx from the static branch."""

    faces = np.asarray(stem.faces, dtype=np.int32)
    edges = np.concatenate(
        (faces[:, (0, 1)], faces[:, (1, 2)], faces[:, (2, 0)]), axis=0
    )
    components = trimesh.graph.connected_components(
        edges,
        nodes=np.arange(len(stem.vertices)),
        min_len=1,
    )
    attachment = np.asarray(attachment_local_point, dtype=np.float64)
    selected_components: list[np.ndarray] = []
    for component in components:
        vertices = np.asarray(stem.vertices[component], dtype=np.float64)
        nearest = float(np.linalg.norm(vertices - attachment, axis=1).min())
        diagonal = float(np.linalg.norm(np.ptp(vertices, axis=0)))
        # The purchased asset stores the two target calyx surfaces as compact
        # disconnected components. The main branch also approaches the joint,
        # but its 20 cm extent keeps it out of this selection.
        if nearest <= 0.002 and diagonal <= 0.060:
            selected_components.append(np.asarray(component, dtype=np.int32))
    if not selected_components:
        return stem, None

    selected_components.sort(key=lambda values: int(values.min()))
    component_ids = np.full(len(stem.vertices), -1, dtype=np.int32)
    for index, component in enumerate(selected_components):
        component_ids[component] = index
    selected_faces = component_ids[faces[:, 0]]
    branch_face_indices = np.flatnonzero(selected_faces < 0)
    if len(branch_face_indices) == 0:
        raise ValueError("target pedicel split cannot consume the entire stem mesh")
    branch = _visual_submesh(
        stem,
        branch_face_indices,
        body_name="branch",
    )
    pedicel = _visual_submesh(
        stem,
        np.flatnonzero(selected_faces >= 0),
        body_name="tomato",
    )
    return branch, pedicel


def load_optional_visual_assets(
    repository_root: Path, cfg: dict[str, Any]
) -> dict[str, VisualMeshAsset]:
    asset_cfg = cfg.get("assets", {})

    def resolve(value: str) -> Path:
        path = Path(value).expanduser()
        return path if path.is_absolute() else repository_root / path

    all_fruit_keys = (
        "fruit_visual_dir",
        "stem_visual_npz",
        "fruit_albedo_texture",
        "visual_metadata",
        "albedo_texture",
    )
    if all(asset_cfg.get(key) for key in all_fruit_keys):
        visual_dir = resolve(str(asset_cfg["fruit_visual_dir"]))
        stem_path = resolve(str(asset_cfg["stem_visual_npz"]))
        fruit_texture_path = resolve(str(asset_cfg["fruit_albedo_texture"]))
        stem_texture_path = resolve(str(asset_cfg["albedo_texture"]))
        metadata_path = resolve(str(asset_cfg["visual_metadata"]))
        required_paths = (
            visual_dir,
            stem_path,
            fruit_texture_path,
            stem_texture_path,
            metadata_path,
        )
        if not all(path.exists() for path in required_paths):
            return {}
        metadata = json.loads(metadata_path.read_text())
        fruit_names = tuple(str(name) for name in metadata["fruit_names"])
        target_name = str(
            cfg.get("scene", {}).get("target_name", metadata["target_name"])
        )
        support_name = str(
            cfg.get("scene", {}).get("support_name", metadata["support_name"])
        )
        if target_name == support_name or not {target_name, support_name} <= set(
            fruit_names
        ):
            raise ValueError(
                "visual target/support must be distinct names in metadata fruit_names"
            )
        fruit_paths = {
            name: visual_dir / f"{name}_visual.npz" for name in fruit_names
        }
        if not all(path.is_file() for path in fruit_paths.values()):
            return {}
        centres = metadata["part_centers_relative_to_target_m"]
        with Image.open(stem_texture_path) as image:
            stem_texture = np.asarray(image.convert("RGBA"), dtype=np.uint8).copy()
        with Image.open(fruit_texture_path) as image:
            fruit_texture = np.asarray(image.convert("RGBA"), dtype=np.uint8).copy()

        stem = _load_visual_mesh(
            stem_path,
            stem_texture,
            stem_texture_path,
            body_name="branch",
        )
        attachment_local_point = np.asarray(
            cfg.get("attachment", {}).get(
                "tomato_local_point", (0.0, 0.0, 0.0)
            ),
            dtype=np.float64,
        )
        branch, target_pedicel = _split_target_pedicel_visual(
            stem,
            attachment_local_point,
        )
        visuals = {"branch": branch}
        if target_pedicel is not None:
            visuals["target_pedicel"] = target_pedicel
        for fruit_name, path in fruit_paths.items():
            if fruit_name == target_name:
                visual_name, body_name, offset = (
                    "tomato",
                    "tomato",
                    (0.0, 0.0, 0.0),
                )
            elif fruit_name == support_name:
                visual_name, body_name, offset = (
                    "support_tomato",
                    "support_tomato",
                    (0.0, 0.0, 0.0),
                )
            else:
                visual_name, body_name = f"cluster_{fruit_name}", "branch"
                raw_offset = np.asarray(centres[fruit_name], dtype=np.float64)
                if raw_offset.shape != (3,) or not np.isfinite(raw_offset).all():
                    raise ValueError(f"invalid visual centre for {fruit_name!r}")
                offset = tuple(float(value) for value in raw_offset)
            visuals[visual_name] = _load_visual_mesh(
                path,
                fruit_texture,
                fruit_texture_path,
                body_name=body_name,
                local_position=offset,
            )
        return visuals

    names = {
        "tomato": asset_cfg.get("target_visual_npz"),
        "branch": asset_cfg.get("cluster_visual_npz"),
    }
    support_value = asset_cfg.get("support_visual_npz")
    if support_value:
        names["support_tomato"] = support_value
    texture_value = asset_cfg.get("albedo_texture")
    if not all(names.values()) or not texture_value:
        return {}

    paths = {name: resolve(str(value)) for name, value in names.items()}
    texture_path = resolve(str(texture_value))
    if not texture_path.is_file() or not all(path.is_file() for path in paths.values()):
        return {}
    with Image.open(texture_path) as image:
        texture = np.asarray(image.convert("RGBA"), dtype=np.uint8).copy()
    return {
        name: _load_visual_mesh(
            path,
            texture,
            texture_path,
            body_name=name,
        )
        for name, path in paths.items()
    }


def _sensor_force_N(sensor: Any) -> float:
    values = np.asarray(sensor.total_force.numpy(), dtype=np.float32).reshape(-1, 3)
    return float(np.linalg.norm(values, axis=1).sum())


def _counterpart_force_N(sensor: Any) -> float:
    """Read only specified counterparts; total_force includes OTHER contacts."""
    if sensor.force_matrix is None:
        raise ValueError('filtered contact evidence requires per-counterpart contact forces')
    values = np.asarray(sensor.force_matrix.numpy(), dtype=np.float32).reshape(-1, 3)
    return float(np.linalg.norm(values, axis=1).sum())


class _TomatoScene:
    def __init__(
        self,
        cfg: dict[str, Any],
        assets: dict[str, Path],
        visual_meshes: dict[str, VisualMeshAsset],
        *,
        device: str,
        repository_root: Path,
        cache_dir: Path,
    ) -> None:
        self.cfg = cfg
        self.scene_cfg = cfg["scene"]
        self.task_cfg = cfg["task"]
        self.device = str(device)
        self.visual_meshes = visual_meshes
        scene = self.scene_cfg
        sim = cfg["sim"]
        attachment = cfg["attachment"]
        solver_cfg = cfg["solver"]
        contact_cfg = cfg["contact"]

        self.tomato_start = np.asarray(scene["tomato_position"], dtype=np.float32)
        self.anchor = np.asarray(scene["stem_anchor"], dtype=np.float32)
        self.anchor_start = self.anchor.copy()
        cluster_quaternion = np.asarray(
            scene.get("cluster_quaternion_xyzw", (0.0, 0.0, 0.0, 1.0)),
            dtype=np.float64,
        )
        if cluster_quaternion.shape != (4,) or not np.isfinite(
            cluster_quaternion
        ).all():
            raise ValueError(
                "scene.cluster_quaternion_xyzw must be a finite XYZW quaternion"
            )
        try:
            self.cluster_quaternion_xyzw = Rotation.from_quat(
                cluster_quaternion
            ).as_quat().astype(np.float32)
        except ValueError as exc:
            raise ValueError(
                "scene.cluster_quaternion_xyzw must be nonzero"
            ) from exc
        self.support_position = self.tomato_start + np.asarray(
            scene["support_tomato_offset_m"], dtype=np.float32
        )
        self.support_position_start = self.support_position.copy()
        if scene.get("support_mode", "fruit") not in {"fruit", "main_stem", "stem_and_fruit"}:
            raise ValueError("scene.support_mode must be fruit, main_stem, or stem_and_fruit")
        self.main_stem_grasp = scene.get("support_mode", "fruit") in {"main_stem", "stem_and_fruit"}
        self.stem_and_fruit = scene.get("support_mode") == "stem_and_fruit"
        self.bunch_wrap_control = bool(cfg['task'].get('bunch_wrap_control', False))
        self.stem_pinch_control = bool(cfg["task"].get("stem_pinch_control", False))
        self.stem_grasp_local = np.asarray(
            scene.get("stem_grasp_offset_m", scene["branch_collision_center_offset_m"]),
            dtype=np.float64,
        )
        self.stem_grasp_position = self.tomato_start + Rotation.from_quat(
            self.cluster_quaternion_xyzw
        ).apply(self.stem_grasp_local)
        self.cluster_offset = np.zeros(3, dtype=np.float32)
        self.previous_cluster_offset = self.cluster_offset.copy()
        hand_model = cfg["robot"].get("hand_model", "wuji")
        if hand_model not in {"wuji", "sharpa"}:
            raise ValueError(f"Unknown robot.hand_model: {hand_model}")
        robot_type = DualSharpaPickRobot if hand_model == "sharpa" else DualWuji2PickRobot
        self.robot = robot_type(
            cfg["robot"],
            repository_root=repository_root,
            tomato_position=self.tomato_start,
            support_position=(self.stem_grasp_position if self.main_stem_grasp
                              else self.support_position),
            harvest_validation_offset=(cfg['script']['support_lift_offset_m']
                                       if self.main_stem_grasp else None),
        )
        self.camera = Gemini435LeCamera(dict(cfg.get("camera", {}) or {}))
        self.wrist_cameras = Gemini305WristCameras(
            dict(cfg.get("wrist_cameras", {}) or {})
        )
        self.camera_sensor_enabled = bool(
            self.camera.sensor_cfg.get("enabled", True)
        )
        self.wrist_camera_sensor_enabled = bool(
            self.wrist_cameras.sensor_cfg.get("enabled", False)
        )
        self.left_tcp = self.robot.default_left_tcp.copy()
        self.right_tcp = self.robot.default_right_tcp.copy()
        self.left_grip = 0.0
        self.right_grip = 0.0
        self.command = np.zeros(10, dtype=np.float32)
        self.detached = False
        self.max_attachment_load = 0.0
        self.max_harvest_distance = 0.0
        self.left_contact_force_N = np.zeros(5, dtype=np.float32)
        self.left_target_contact_force_N = np.zeros(5, dtype=np.float32)
        self.right_contact_force_N = np.zeros(5, dtype=np.float32)
        self.right_stem_contact_force_N = np.zeros(5, dtype=np.float32)
        self.support_force_indices = [
            self.robot.tactile_fingers.index(finger)
            for finger in self.robot.right_force_fingers
        ]
        self.wrap_contact_targets = None
        if self.bunch_wrap_control:
            from .bunch_wrap import contact_targets
            self.wrap_contact_targets = contact_targets(self.task_cfg, self.robot.right_force_fingers)
        contact_fingers = self.task_cfg.get("minimum_support_contact_fingers", 2)
        if (isinstance(contact_fingers, bool)
                or not isinstance(contact_fingers, int)
                or not 2 <= contact_fingers <= len(self.support_force_indices)):
            raise ValueError("minimum_support_contact_fingers must be an integer between 2 and the support finger count")
        for key, default in (("minimum_support_finger_contact_N", 0.5),
                             ("support_contact_gain_s_N", 0.03),
                             ("support_free_closure_rate_s", 0.5),
                             ("harvest_retention_contact_target_N",
                              self.task_cfg.get("harvest_contact_target_N", 3.0))):
            value = float(self.task_cfg.get(key, default))
            if not np.isfinite(value) or value <= 0.0:
                raise ValueError(f"{key} must be finite and positive")
        minimum_wrap = float(self.task_cfg.get("minimum_support_wrap_closure", 0.0))
        if (not np.isfinite(minimum_wrap) or minimum_wrap < 0.0
                or minimum_wrap > float(self.task_cfg.get("support_maximum_closure", 1.15))):
            raise ValueError("minimum_support_wrap_closure must be between zero and support_maximum_closure")
        if minimum_wrap > 0.0 and not any(
            f in ("middle", "ring", "pinky") for f in self.robot.right_force_fingers
        ):
            raise ValueError("minimum_support_wrap_closure requires a supporting middle, ring, or pinky finger")
        self.right_grasp_force_ema = np.zeros(len(self.support_force_indices))
